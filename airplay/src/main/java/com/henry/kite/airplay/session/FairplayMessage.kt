    private val FORWARD_SBOX = IntArray(256).also { table ->
        for (encrypted in INVERSE_SBOX.indices) table[INVERSE_SBOX[encrypted]] = encrypted
    }

    /** Decrypts the 128-byte body at message[16..144) into plaintext. */
    fun decryptMessage(message: IntArray, plaintext: IntArray) {
        val mode = message[12]
        val state = IntArray(16)
        for (block in 0 until 8) {
            val start = 16 + block * 16
            for (i in 0 until 16) state[i] = message[start + i]
            decryptBlock(state, mode)

            val chain = if (block > 0) message else MESSAGE_IV[mode]
            val chainOffset = if (block > 0) start - 16 else 0
            for (i in 0 until 16) plaintext[block * 16 + i] = state[i] xor chain[chainOffset + i]
        }
    }

    /** Inverse of [decryptMessage]: encrypts one 128-byte SAP body. */
    fun encryptMessage(mode: Int, plaintext: IntArray, encrypted: IntArray) {
        var chain: IntArray = MESSAGE_IV[mode]
        val state = IntArray(16)
        for (block in 0 until 8) {
            val start = block * 16
            for (i in 0 until 16) state[i] = plaintext[start + i] xor chain[i]
            encryptBlock(state, mode)
            for (i in 0 until 16) encrypted[start + i] = state[i]
            chain = encrypted.copyOfRange(start, start + 16)
        }
    }

    private fun decryptBlock(state: IntArray, mode: Int) {
        xorRoundKey(state, ROUND_KEY_10)
        for (round in 9 downTo 1) {
            inverseShiftRows(state)
            for (i in 0 until 16) state[i] = INVERSE_SBOX[state[i]]
            xorRoundKey(state, MIDDLE_KEYS[mode][round - 1])
            inverseMixColumns(state)
        }
        inverseShiftRows(state)
        for (i in 0 until 16) state[i] = INVERSE_SBOX[state[i]]
        xorRoundKey(state, ROUND_KEY_0)
    }

    private fun encryptBlock(state: IntArray, mode: Int) {
        xorRoundKey(state, ROUND_KEY_0)
        for (i in 0 until 16) state[i] = FORWARD_SBOX[state[i]]
        shiftRows(state)
        for (round in 0 until 9) {
            mixColumns(state)
            xorRoundKey(state, MIDDLE_KEYS[mode][round])
            for (i in 0 until 16) state[i] = FORWARD_SBOX[state[i]]
            shiftRows(state)
        }
        xorRoundKey(state, ROUND_KEY_10)
    }

    private fun xorRoundKey(state: IntArray, key: IntArray) {
        for (i in 0 until 16) state[i] = state[i] xor key[i]
    }

    private fun inverseShiftRows(state: IntArray) {
        val previous = state.copyOf()
        for (row in 0 until 4) {
            for (column in 0 until 4) {
                state[4 * column + row] = previous[4 * ((column - row + 4) and 3) + row]
            }
        }
    }

    private fun shiftRows(state: IntArray) {
        val previous = state.copyOf()
        for (row in 0 until 4) {
            for (column in 0 until 4) {
                state[4 * column + row] = previous[4 * ((column + row) and 3) + row]
            }
        }
    }

    private fun inverseMixColumns(state: IntArray) {
        for (column in 0 until 4) {
            val offset = column * 4
            val a = state[offset]
            val b = state[offset + 1]
            val c = state[offset + 2]
            val d = state[offset + 3]
            state[offset] = gf(a, 14) xor gf(b, 11) xor gf(c, 13) xor gf(d, 9)
            state[offset + 1] = gf(a, 9) xor gf(b, 14) xor gf(c, 11) xor gf(d, 13)
            state[offset + 2] = gf(a, 13) xor gf(b, 9) xor gf(c, 14) xor gf(d, 11)
            state[offset + 3] = gf(a, 11) xor gf(b, 13) xor gf(c, 9) xor gf(d, 14)
        }
    }

    private fun mixColumns(state: IntArray) {
        for (column in 0 until 4) {
            val offset = column * 4
            val a = state[offset]
            val b = state[offset + 1]
            val c = state[offset + 2]
            val d = state[offset + 3]
            state[offset] = gf(a, 2) xor gf(b, 3) xor c xor d
            state[offset + 1] = a xor gf(b, 2) xor gf(c, 3) xor d
            state[offset + 2] = a xor b xor gf(c, 2) xor gf(d, 3)
            state[offset + 3] = gf(a, 3) xor b xor c xor gf(d, 2)
        }
    }

    private fun gf(a: Int, b: Int): Int {
        var value = a and 0xFF
        var multiplier = b
        var product = 0
        while (multiplier != 0) {
            if (multiplier and 1 != 0) product = product xor value
            val high = value and 0x80
            value = (value shl 1) and 0xFF
            if (high != 0) value = value xor 0x1b
            multiplier = multiplier shr 1
        }
        return product
    }
